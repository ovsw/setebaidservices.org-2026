#!/usr/bin/env node
// Import the two-tone navigation icons from the legacy canadianadventurecamp.com
// website into studio/schemas/inputs/camp-icon-catalog.ts.
//
// The legacy site (Nuxt) shipped its icons as one SVG sprite. Its `*-duotone`
// symbols are two `<path>` elements: a primary shape and a secondary shape at
// 40% opacity, both drawn with currentColor. This script keeps only the two
// path outlines and the viewBox, so the Studio picker and the website can
// render the icon in any colour.
//
// Usage: pnpm --dir studio generate:camp-icons [sprite-url-or-file]
// The generated file is committed; rerun only when the icon set changes.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

const DEFAULT_SPRITE_URL =
  "https://www.canadianadventurecamp.com/_nuxt/719572abed0e23513c1d8ca302ebe0ab.svg";
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const catalogOutputPath = path.resolve(
  scriptDirectory,
  "../schemas/inputs/camp-icon-catalog.ts",
);

async function readSprite(source) {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source);
    if (!response.ok) {
      throw new Error(`Sprite download failed with ${response.status}`);
    }
    return response.text();
  }
  return readFile(source, "utf8");
}

function attribute(markup, name) {
  return markup.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
}

export function extractCampIcons(sprite) {
  const icons = [];
  const symbolPattern = /<symbol([^>]*)>([\s\S]*?)<\/symbol>/g;

  for (const [, attributes, body] of sprite.matchAll(symbolPattern)) {
    const id = attribute(attributes, "id");
    const viewBox = attribute(attributes, "viewBox");
    if (!id?.endsWith("-duotone") || !viewBox) continue;

    const paths = [...body.matchAll(/<path([^>]*)\/?>/g)].map(([, pathAttributes]) => ({
      d: attribute(pathAttributes, "d"),
      secondary: attribute(pathAttributes, "class") === "fa-secondary",
    }));
    const primary = paths.find((item) => !item.secondary)?.d;
    const secondary = paths.find((item) => item.secondary)?.d;
    if (paths.length !== 2 || !primary || !secondary) {
      throw new Error(`Symbol "${id}" is not a two-path duotone icon`);
    }

    icons.push({
      name: id.replace(/^i-/, "").replace(/-duotone$/, ""),
      viewBox,
      primary,
      secondary,
    });
  }

  icons.sort((left, right) => left.name.localeCompare(right.name));
  return icons;
}

export function buildCampIconCatalog(icons, source) {
  // Every sprite-derived value goes through JSON.stringify so a stray
  // backslash or line break in the source can never alter the generated code.
  const entries = icons
    .map(
      (icon) =>
        `  ${JSON.stringify(icon.name)}: {\n    viewBox: ${JSON.stringify(icon.viewBox)},\n    primary: ${JSON.stringify(icon.primary)},\n    secondary: ${JSON.stringify(icon.secondary)},\n  },`,
    )
    .join("\n");
  const sourceComment = String(source).replace(/[\r\n\u2028\u2029]+/g, " ");

  return `// Generated by studio/scripts/import-camp-icons.mjs from\n// ${sourceComment}\n// Two-tone icons carried over from the legacy website; do not edit by hand.\n\nexport const campIconArtwork = {\n${entries}\n} as const;\n`;
}

async function run() {
  const source = process.argv[2] || DEFAULT_SPRITE_URL;
  const icons = extractCampIcons(await readSprite(source));
  if (!icons.length) throw new Error("No duotone symbols found in the sprite");
  await writeFile(catalogOutputPath, buildCampIconCatalog(icons, source));
  console.log(`Wrote ${icons.length} camp icons to ${catalogOutputPath}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  run().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
